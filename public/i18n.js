// ─── Engine ──────────────────────────────────────────────────────────────────
const LANG_KEY = "rcLang";
export let currentLang = localStorage.getItem(LANG_KEY) || "es";

/** Translate a key, optionally interpolating {placeholder} values */
export function t(key, vars = {}) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.es;
  let str = dict[key] ?? TRANSLATIONS.es[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    str = str.replaceAll(`{${k}}`, String(v));
  }
  return str;
}

/** Switch language, persist, and re-render the DOM */
export function setLang(lang) {
  if (!TRANSLATIONS[lang]) return;
  currentLang = lang;
  localStorage.setItem(LANG_KEY, lang);
  document.documentElement.lang = lang;
  applyStaticTranslations();
  // Dispatch event so app.js can re-render dynamic content
  window.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}

/** Apply translations to elements with data-i18n attribute */
export function applyStaticTranslations() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    const translation = t(key);
    if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
      if (el.placeholder !== undefined) el.placeholder = translation;
    } else if (el.dataset.i18nAttr) {
      el.setAttribute(el.dataset.i18nAttr, translation);
    } else {
      el.textContent = translation;
    }
  });

  // Translate option elements with data-i18n
  document.querySelectorAll("option[data-i18n]").forEach(opt => {
    opt.textContent = t(opt.dataset.i18n);
  });
}

